/* 0x3a9e5(a, b): the angle of (b, a) - a the sine side - in 16.16 degrees: |a| / |b| (the smaller over the larger) as
 * (n << 24) / d, table entry (q >> 16) + its slope x (q & 0xffff) >> 16 rounded; 90 - it when |a| > |b|, 180 - it when
 * b < 0, negated when a < 0; |a| == |b|: 45 */
static inline int32_t dos_atan2(int32_t a, int32_t b)
{
    uint32_t n = (uint32_t)(a < 0 ? -(int64_t)a : a), d = (uint32_t)(b < 0 ? -(int64_t)b : b), t;
    int fl = (a < 0 ? 1 : 0) | (b < 0 ? 2 : 0);
    int32_t r;
    if (n >= d) {
        if (n == d) { r = 0x2d0000; goto sign; }
        t = n; n = d; d = t; fl |= 4;
    }
    if (n == 0) r = 0;
    else {
        uint32_t q = (uint32_t)(((uint64_t)n << 24) / d), i = q >> 16, f = q & 0xffff;
        uint32_t l = f * (uint32_t)(DOS_ATAN[i + 1] - DOS_ATAN[i]);
        r = DOS_ATAN[i] + (int32_t)(l >> 16) + (int32_t)((l >> 15) & 1);
    }
sign:
    if (fl & 4) r = 0x5a0000 - r;
    if (fl & 2) r = 0xb40000 - r;
    if (fl & 1) r = -r;
    return r;
}

/* 0x2ab60 divides the dominant horizontal component by its projected
 * angle, then divides the horizontal length by the pitch cosine. */
static inline int32_t dos_level_distance(int32_t dx, int32_t dz)
{
    int32_t yaw = dos_atan2(dx, dz);
    int use_x = abs(dx) > abs(dz);
    int32_t component = use_x ? dx : dz;
    int32_t direction = use_x ? dos_sin(yaw) : dos_cos(yaw);
    return direction ? (int32_t)((int64_t)component * 536870912 / direction) : 0;
}

static inline int32_t dos_slant_distance(int32_t level, int32_t dy)
{
    int32_t direction = dos_cos(dos_atan2(dy, level));
    return direction ? (int32_t)((int64_t)level * 536870912 / direction) : 0;
}

